//! Storage integrity verifier module (Rclone `check` equivalent).
//!
//! Provides bidirectional integrity checking between a local directory and a remote
//! storage backend, comparing file existence, sizes, and optional cryptographic checksums.

use crate::traits::{StorageBackend, StorageError};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, HashSet};
use std::path::Path;
use std::time::Instant;

/// Details of a mismatched file detected during integrity verification.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct VerificationMismatch {
    pub relative_path: String,
    pub local_size: u64,
    pub remote_size: u64,
    pub local_checksum: Option<String>,
    pub remote_checksum: Option<String>,
    pub reason: String,
}

/// Comprehensive report generated by the integrity verifier.
#[derive(Debug, Clone, Serialize, Deserialize, Default, PartialEq, Eq)]
pub struct VerificationReport {
    /// Files that match perfectly in size (and checksum, if requested).
    pub matched: Vec<String>,
    /// Files with discrepancies (size or checksum mismatch).
    pub mismatched: Vec<VerificationMismatch>,
    /// Files present locally but missing on the remote storage.
    pub missing_on_remote: Vec<String>,
    /// Files present on the remote storage but missing locally.
    pub missing_on_local: Vec<String>,
    /// Total number of distinct files examined across both targets.
    pub total_files_checked: usize,
    /// Total bytes of matching files verified.
    pub total_bytes_matched: u64,
    /// Duration of the verification process in milliseconds.
    pub duration_ms: u64,
}

impl VerificationReport {
    /// Returns true if both local and remote targets are in complete synchronization.
    pub fn is_identical(&self) -> bool {
        self.mismatched.is_empty()
            && self.missing_on_remote.is_empty()
            && self.missing_on_local.is_empty()
    }
}

const MAX_VERIFY_DEPTH: usize = 64;

/// Recursively collects all local files and their sizes starting from `root`.
/// Uses `symlink_metadata` to avoid following symlink cycles and enforces a maximum depth.
async fn collect_local_files(
    root: &Path,
    current_dir: &Path,
    results: &mut HashMap<String, u64>,
    depth: usize,
) -> Result<(), StorageError> {
    if depth > MAX_VERIFY_DEPTH {
        return Ok(());
    }
    let mut entries = tokio::fs::read_dir(current_dir).await?;
    while let Some(entry) = entries.next_entry().await? {
        let meta = tokio::fs::symlink_metadata(entry.path()).await?;
        if meta.is_symlink() {
            continue;
        }
        let path = entry.path();
        if meta.is_dir() {
            Box::pin(collect_local_files(root, &path, results, depth + 1)).await?;
        } else if meta.is_file() {
            if let Ok(rel) = path.strip_prefix(root) {
                let rel_str = rel.to_string_lossy().replace('\\', "/");
                results.insert(rel_str, meta.len());
            }
        }
    }
    Ok(())
}

/// Recursively collects all remote items starting from `remote_prefix` using the shared tree walker.
async fn collect_remote_files(
    backend: &(dyn StorageBackend + Send + Sync),
    remote_prefix: &str,
    results: &mut HashMap<String, (u64, Option<String>)>,
) -> Result<(), StorageError> {
    let items = crate::providers::utils::walk_remote_tree(backend, remote_prefix).await?;
    for item in items {
        if !item.is_dir {
            let path_str = item.path.to_string_lossy().replace('\\', "/");
            let key = path_str.trim_start_matches('/').to_string();
            results.insert(key, (item.size, item.checksum));
        }
    }
    Ok(())
}

/// Verifies integrity between a local directory and a remote storage backend.
///
/// # Arguments
/// * `backend` - The storage backend to compare against.
/// * `local_root` - Local folder directory path.
/// * `remote_path` - Remote storage directory path (can be empty or `"/"` for root).
/// * `compare_checksums` - Whether to compute and compare cryptographic checksums.
pub async fn verify_integrity(
    backend: &(dyn StorageBackend + Send + Sync),
    local_root: &Path,
    remote_path: &str,
    compare_checksums: bool,
) -> Result<VerificationReport, StorageError> {
    let start_time = Instant::now();
    let mut local_files = HashMap::new();
    if local_root.exists() {
        collect_local_files(local_root, local_root, &mut local_files, 0).await?;
    }

    let mut remote_files = HashMap::new();
    let clean_remote = remote_path.trim_matches('/');
    collect_remote_files(backend, clean_remote, &mut remote_files).await?;

    let mut all_paths = HashSet::new();
    for p in local_files.keys() {
        all_paths.insert(p.clone());
    }
    for p in remote_files.keys() {
        let normalized = if !clean_remote.is_empty() && p.starts_with(clean_remote) {
            p[clean_remote.len()..].trim_start_matches('/').to_string()
        } else {
            p.clone()
        };
        all_paths.insert(normalized);
    }

    let mut report = VerificationReport {
        total_files_checked: all_paths.len(),
        ..Default::default()
    };

    for rel_path in all_paths {
        let local_size = local_files.get(&rel_path).copied();
        let remote_key = if clean_remote.is_empty() {
            rel_path.clone()
        } else {
            format!("{}/{}", clean_remote, rel_path)
        };
        let remote_entry = remote_files.get(&remote_key);

        match (local_size, remote_entry) {
            (Some(l_size), Some((r_size, r_checksum))) => {
                let r_size = *r_size;
                if l_size != r_size {
                    report.mismatched.push(VerificationMismatch {
                        relative_path: rel_path,
                        local_size: l_size,
                        remote_size: r_size,
                        local_checksum: None,
                        remote_checksum: r_checksum.clone(),
                        reason: format!(
                            "Size mismatch: local {} bytes, remote {} bytes",
                            l_size, r_size
                        ),
                    });
                } else if compare_checksums {
                    let full_local = local_root.join(&rel_path);
                    let local_sum = backend.compute_local_checksum(&full_local).await?;
                    if let (Some(l_sum), Some(r_sum)) = (&local_sum, r_checksum) {
                        if l_sum != r_sum {
                            report.mismatched.push(VerificationMismatch {
                                relative_path: rel_path,
                                local_size: l_size,
                                remote_size: r_size,
                                local_checksum: Some(l_sum.clone()),
                                remote_checksum: Some(r_sum.clone()),
                                reason: format!(
                                    "Checksum mismatch: local {}, remote {}",
                                    l_sum, r_sum
                                ),
                            });
                            continue;
                        }
                    }
                    report.matched.push(rel_path);
                    report.total_bytes_matched += l_size;
                } else {
                    report.matched.push(rel_path);
                    report.total_bytes_matched += l_size;
                }
            }
            (Some(_), None) => {
                report.missing_on_remote.push(rel_path);
            }
            (None, Some(_)) => {
                report.missing_on_local.push(rel_path);
            }
            (None, None) => unreachable!(),
        }
    }

    report.matched.sort();
    report.missing_on_remote.sort();
    report.missing_on_local.sort();
    report
        .mismatched
        .sort_by(|a, b| a.relative_path.cmp(&b.relative_path));
    report.duration_ms = start_time.elapsed().as_millis() as u64;

    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::providers::local_sim::LocalSimulation;
    use tempfile::tempdir;

    #[tokio::test]
    async fn test_verify_integrity_identical() {
        let temp_local = tempdir().unwrap();
        let temp_remote = tempdir().unwrap();

        let file_a = temp_local.path().join("file.txt");
        tokio::fs::write(&file_a, b"hello world").await.unwrap();

        let backend = LocalSimulation::new(temp_remote.path().to_path_buf(), "test".to_string());
        backend.upload(&file_a, "file.txt").await.unwrap();

        let report = verify_integrity(&backend, temp_local.path(), "", false)
            .await
            .unwrap();

        assert!(report.is_identical());
        assert_eq!(report.matched.len(), 1);
        assert_eq!(report.matched[0], "file.txt");
        assert_eq!(report.total_bytes_matched, 11);
    }

    #[tokio::test]
    async fn test_verify_integrity_discrepancies() {
        let temp_local = tempdir().unwrap();
        let temp_remote = tempdir().unwrap();

        // File 1: identical
        let file_1 = temp_local.path().join("same.txt");
        tokio::fs::write(&file_1, b"same content").await.unwrap();

        // File 2: local only
        let file_2 = temp_local.path().join("local_only.txt");
        tokio::fs::write(&file_2, b"local data").await.unwrap();

        let backend = LocalSimulation::new(temp_remote.path().to_path_buf(), "test".to_string());
        backend.upload(&file_1, "same.txt").await.unwrap();

        // File 3: remote only
        let temp_upload = tempdir().unwrap();
        let remote_file = temp_upload.path().join("temp_remote.txt");
        tokio::fs::write(&remote_file, b"remote data")
            .await
            .unwrap();
        backend
            .upload(&remote_file, "remote_only.txt")
            .await
            .unwrap();

        let report = verify_integrity(&backend, temp_local.path(), "", false)
            .await
            .unwrap();

        assert!(!report.is_identical());
        assert_eq!(report.matched, vec!["same.txt"]);
        assert_eq!(report.missing_on_remote, vec!["local_only.txt"]);
        assert_eq!(report.missing_on_local, vec!["remote_only.txt"]);
    }
}
